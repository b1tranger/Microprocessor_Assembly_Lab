<#
.SYNOPSIS
    Generates include/default_assets.h from files inside data/ (data/default/, data/www/).
.DESCRIPTION
    Scans data/ recursively and generates C++ PROGMEM byte arrays and an asset registry table.
    Ensures files in default/ and www/ are marked as isProtected = true.
#>

$scriptDir = if ($PSScriptRoot) { $PSScriptRoot } else { Split-Path -Parent $MyInvocation.MyCommand.Path }
$projectDir = Split-Path -Parent $scriptDir
$dataDir = Join-Path $projectDir "data"
$outputHeader = Join-Path $projectDir "include\default_assets.h"

if (-not (Test-Path $dataDir)) {
    Write-Warning "[generate_assets] data directory not found at $dataDir"
    exit 0
}

$targetDirs = @(
    (Join-Path $dataDir "default"),
    (Join-Path $dataDir "www")
)

$files = @()
foreach ($td in $targetDirs) {
    if (Test-Path $td) {
        $files += Get-ChildItem -Path $td -Recurse -File | Where-Object { $_.Name -notlike ".*" }
    }
}
$files = $files | Sort-Object FullName
$assets = @()
$idx = 0

foreach ($f in $files) {
    # Compute relative path
    $relPath = $f.FullName.Substring($dataDir.Length).TrimStart('\', '/').Replace('\', '/')
    $sdPath = "/" + $relPath
    $isProtected = $relPath.StartsWith("default/") -or $relPath.StartsWith("www/")
    $bytes = [System.IO.File]::ReadAllBytes($f.FullName)
    $varName = "ASSET_DATA_$idx"

    $assets += [PSCustomObject]@{
        VarName = $varName
        SdPath = $sdPath
        IsProtected = $isProtected
        Size = $bytes.Length
        Bytes = $bytes
    }
    $idx++
}

$sb = [System.Text.StringBuilder]::new()
[void]$sb.AppendLine("// ============================================================================")
[void]$sb.AppendLine("// AUTO-GENERATED BY scripts/generate_assets.ps1 / generate_assets.py")
[void]$sb.AppendLine("// DO NOT EDIT MANUALLY - EDIT FILES IN data/default/ OR data/www/ INSTEAD")
[void]$sb.AppendLine("// ============================================================================")
[void]$sb.AppendLine("#ifndef DEFAULT_ASSETS_H")
[void]$sb.AppendLine("#define DEFAULT_ASSETS_H")
[void]$sb.AppendLine("")
[void]$sb.AppendLine("#include <Arduino.h>")
[void]$sb.AppendLine("")
[void]$sb.AppendLine("struct EmbeddedAsset {")
[void]$sb.AppendLine("  const char* sdPath;")
[void]$sb.AppendLine("  const uint8_t* data;")
[void]$sb.AppendLine("  size_t size;")
[void]$sb.AppendLine("  bool isProtected;")
[void]$sb.AppendLine("};")
[void]$sb.AppendLine("")

foreach ($asset in $assets) {
    [void]$sb.AppendLine("// File: $($asset.SdPath) ($($asset.Size) bytes)")
    [void]$sb.AppendLine("static const uint8_t $($asset.VarName)[] PROGMEM = {")
    
    $hexChunks = [System.Collections.Generic.List[string]]::new()
    for ($i = 0; $i -lt $asset.Bytes.Length; $i += 16) {
        $count = [Math]::Min(16, $asset.Bytes.Length - $i)
        $sub = for ($j = 0; $j -lt $count; $j++) { "0x{0:x2}" -f $asset.Bytes[$i + $j] }
        $hexChunks.Add("  " + ($sub -join ", "))
    }
    [void]$sb.AppendLine(($hexChunks -join ",`n"))
    [void]$sb.AppendLine("};")
    [void]$sb.AppendLine("")
}

[void]$sb.AppendLine("// Registry of all default embedded assets")
[void]$sb.AppendLine("static const EmbeddedAsset EMBEDDED_ASSETS[] = {")
foreach ($asset in $assets) {
    $pStr = if ($asset.IsProtected) { "true" } else { "false" }
    [void]$sb.AppendLine("  { `"$($asset.SdPath)`", $($asset.VarName), sizeof($($asset.VarName)), $pStr },")
}
[void]$sb.AppendLine("};")
[void]$sb.AppendLine("static const size_t EMBEDDED_ASSET_COUNT = $($assets.Count);")
[void]$sb.AppendLine("")
[void]$sb.AppendLine("#endif // DEFAULT_ASSETS_H")
[void]$sb.AppendLine("")

[System.IO.File]::WriteAllText($outputHeader, $sb.ToString(), [System.Text.Encoding]::UTF8)
Write-Host "[generate_assets] Successfully generated $outputHeader with $($assets.Count) assets." -ForegroundColor Green

